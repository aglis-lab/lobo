use renderer::{Offset, Size, TextPaint};
use vello_cpu::kurbo::{BezPath, Rect};

/// Measures single-line `text` using the built-in fixed-pitch 5×7 glyph grid.
pub(crate) fn measure_text(text: &str, paint: &TextPaint) -> Size {
  let size = paint.size.max(1.0);
  Size::new(text.chars().count() as f32 * size * 0.6, size)
}

/// Builds a vector path for single-line `text` with top-left at `origin`.
pub(crate) fn glyph_path(origin: Offset, text: &str, paint: &TextPaint) -> BezPath {
  let mut path = BezPath::new();
  if text.is_empty() {
    return path;
  }
  let size = paint.size.max(1.0);
  let advance = size * 0.6;
  let cell_w = advance / 6.0;
  let cell_h = size / 8.0;
  let pixel_w = if paint.bold { cell_w * 1.25 } else { cell_w };
  let y_base = origin.y + cell_h * 0.5;

  for (idx, ch) in text.chars().enumerate() {
    let x_base = origin.x + idx as f32 * advance;
    let rows = glyph_bitmap(ch);
    for (row_idx, &bits) in rows.iter().enumerate() {
      if bits == 0 {
        continue;
      }
      let shear = if paint.italic { (6 - row_idx as i32) as f32 * cell_w * 0.22 } else { 0.0 };
      let y0 = f64::from(y_base + row_idx as f32 * cell_h);
      let y1 = y0 + f64::from(cell_h);
      for col in 0..5 {
        if (bits & (1 << (4 - col))) != 0 {
          let x0 = f64::from(x_base + col as f32 * cell_w + shear);
          let x1 = x0 + f64::from(pixel_w);
          append_rect(&mut path, Rect::new(x0, y0, x1, y1));
        }
      }
    }
  }

  if paint.underline {
    let total_w = text.chars().count() as f32 * advance;
    let uy = f64::from(origin.y + size - cell_h * 0.7);
    let uh = f64::from((cell_h * 0.6).max(1.0));
    append_rect(
      &mut path,
      Rect::new(f64::from(origin.x), uy, f64::from(origin.x + total_w), uy + uh),
    );
  }

  path
}

fn append_rect(path: &mut BezPath, r: Rect) {
  path.move_to((r.x0, r.y0));
  path.line_to((r.x1, r.y0));
  path.line_to((r.x1, r.y1));
  path.line_to((r.x0, r.y1));
  path.close_path();
}

